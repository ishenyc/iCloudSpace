-- Canonical installation schema, version 1. Historical readers do not run here.
CREATE SCHEMA space;

-- Signed Unix nanoseconds. No timestamp cast may truncate imported instants.
CREATE DOMAIN space.instant_ns AS bigint;
CREATE FUNCTION space.clock_ns() RETURNS space.instant_ns
LANGUAGE sql VOLATILE SET search_path = pg_catalog AS $$
    SELECT floor(extract(epoch FROM clock_timestamp()) * 1000000000)::bigint
$$;

CREATE TABLE space.schema_migrations (
    version integer PRIMARY KEY CHECK (version > 0),
    name text NOT NULL CHECK (name <> ''),
    checksum text NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    catalog_checksum text NOT NULL CHECK (catalog_checksum ~ '^[0-9a-f]{64}$'),
    applied_at space.instant_ns NOT NULL DEFAULT space.clock_ns()
);
CREATE FUNCTION space.protect_migration_history() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
    RAISE EXCEPTION 'space migration history is append-only' USING ERRCODE = '55000';
END
$$;
CREATE TRIGGER migration_history_immutable
    BEFORE UPDATE OR DELETE OR TRUNCATE ON space.schema_migrations
    FOR EACH STATEMENT EXECUTE FUNCTION space.protect_migration_history();

CREATE TABLE space.installation (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    installation_id text NOT NULL UNIQUE CHECK (installation_id <> ''),
    management_path text NOT NULL CHECK (left(management_path, 1) = '/'),
    configuration_revision bigint NOT NULL CHECK (configuration_revision > 0),
    created_at space.instant_ns NOT NULL,
    writes_enabled boolean NOT NULL DEFAULT false
);
CREATE TABLE space.key_binding (
    singleton boolean PRIMARY KEY DEFAULT true REFERENCES space.installation(singleton),
    binding_version integer NOT NULL CHECK (binding_version > 0),
    key_id text NOT NULL CHECK (key_id <> ''),
    proof bytea NOT NULL CHECK (octet_length(proof) > 0),
    created_at space.instant_ns NOT NULL
);
CREATE TABLE space.installation_settings (
    singleton boolean PRIMARY KEY DEFAULT true REFERENCES space.installation(singleton),
    http_address text NOT NULL,
    imaps_address text NOT NULL,
    public_host text NOT NULL,
    tls_certificate_ref text NOT NULL,
    tls_private_key_ref text NOT NULL,
    archive_capacity_bytes bigint NOT NULL CHECK (archive_capacity_bytes >= 0),
    sync_concurrency integer NOT NULL CHECK (sync_concurrency > 0),
