CREATE INDEX mailbox_entries_latest ON space.mailbox_entries(address_id, visible_at DESC, id DESC);
CREATE INDEX mailbox_entries_unconsumed ON space.mailbox_entries(address_id, visible_at DESC, id DESC) WHERE consumed_at IS NULL;
CREATE TABLE space.address_snapshots (
    address_id bigint PRIMARY KEY,
    source_id bigint NOT NULL,
    message_id bigint NOT NULL,
    entry_id bigint,
    view_key text,
    view_scope_address_id bigint NOT NULL DEFAULT 0 CHECK (view_scope_address_id = 0 OR view_scope_address_id = address_id),
    selected_at space.instant_ns NOT NULL,
    consumed_at space.instant_ns,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE,
    FOREIGN KEY (source_id, message_id) REFERENCES space.source_messages(source_id, id) ON DELETE CASCADE,
    FOREIGN KEY (source_id, message_id, view_key, view_scope_address_id) REFERENCES space.message_views(source_id, message_id, view_key, scope_address_id),
    FOREIGN KEY (source_id, address_id, entry_id, message_id) REFERENCES space.mailbox_entries(source_id, address_id, id, message_id) ON DELETE SET NULL (entry_id)
