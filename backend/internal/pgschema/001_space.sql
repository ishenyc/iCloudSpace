CREATE TABLE space.address_backfills (
    source_id bigint NOT NULL,
    address_id bigint NOT NULL,
    mailbox_name text NOT NULL CHECK (mailbox_name <> ''),
    source_generation bigint NOT NULL CHECK (source_generation > 0),
    scan_epoch bigint NOT NULL CHECK (scan_epoch > 0),
    uid_validity bigint NOT NULL CHECK (uid_validity BETWEEN 1 AND 4294967295),
    lower_uid bigint NOT NULL CHECK (lower_uid BETWEEN 0 AND 4294967295),
    captured_upper_uid bigint NOT NULL CHECK (captured_upper_uid BETWEEN 0 AND 4294967295),
    committed_uid bigint NOT NULL CHECK (committed_uid BETWEEN 0 AND 4294967295),
    state text NOT NULL CHECK (state IN ('pending', 'scanning', 'complete', 'cancelled')),
    initialized boolean NOT NULL DEFAULT false,
    owner_key text,
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL,
    PRIMARY KEY (address_id, source_generation, mailbox_name, scan_epoch),
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE,
    CHECK (lower_uid <= committed_uid AND committed_uid <= captured_upper_uid)
);
CREATE INDEX backfills_pending ON space.address_backfills(source_id, state, address_id);
-- This receipt owns only an intake checkpoint. It is not a task queue.
-- A prepared source prevents a restart from inventing replacement blob IDs.
CREATE TABLE space.intake_batches (
    batch_key text PRIMARY KEY CHECK (batch_key <> ''),
    source_id bigint NOT NULL REFERENCES space.mail_sources(id) ON DELETE CASCADE,
    plan jsonb NOT NULL CHECK (jsonb_typeof(plan) = 'object'),
    plan_digest bytea NOT NULL CHECK (octet_length(plan_digest) = 32),
    checkpoint_digest bytea CHECK (octet_length(checkpoint_digest) = 32),
    state text NOT NULL CHECK (state IN ('prepared', 'committed', 'abandoned')),
    created_at space.instant_ns NOT NULL,
    committed_at space.instant_ns,
    abandoned_at space.instant_ns,
    CHECK ((state = 'committed') = (checkpoint_digest IS NOT NULL)),
    CHECK ((state = 'committed') = (committed_at IS NOT NULL)),
