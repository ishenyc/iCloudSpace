    email text NOT NULL,
    display_name text NOT NULL,
    evidence text NOT NULL CHECK (evidence IN ('strong', 'weak', 'display')),
    PRIMARY KEY (message_id, role, ordinal)
);
CREATE TABLE space.message_codes (
    message_id bigint NOT NULL REFERENCES space.source_messages(id) ON DELETE CASCADE,
    ordinal integer NOT NULL CHECK (ordinal >= 0),
    code text NOT NULL CHECK (code <> ''),
    PRIMARY KEY (message_id, ordinal)
);
CREATE TABLE space.mailbox_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL,
    address_id bigint NOT NULL,
    message_id bigint NOT NULL,
    local_uid bigint NOT NULL CHECK (local_uid BETWEEN 1 AND 4294967295),
    visible_at space.instant_ns NOT NULL,
    snapshot_selected_at space.instant_ns,
    consumed_at space.instant_ns,
    retained_code text,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE,
    FOREIGN KEY (source_id, message_id) REFERENCES space.source_messages(source_id, id) ON DELETE CASCADE,
    UNIQUE (address_id, local_uid),
    UNIQUE (address_id, message_id),
    UNIQUE (source_id, address_id, id),
    UNIQUE (source_id, address_id, id, message_id)
