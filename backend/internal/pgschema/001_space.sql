    allow_weak_recipient_evidence boolean NOT NULL DEFAULT false,
    updated_at space.instant_ns NOT NULL
);
CREATE TABLE space.installation_secrets (
    purpose text PRIMARY KEY CHECK (purpose IN ('session_signing', 'csrf_signing', 'oauth_signing')),
    envelope bytea NOT NULL CHECK (octet_length(envelope) > 0),
    revision bigint NOT NULL CHECK (revision > 0)
);
CREATE TABLE space.operators (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_name text NOT NULL UNIQUE CHECK (login_name <> ''),
    password_encoding text NOT NULL CHECK (password_encoding <> ''),
    session_epoch bigint NOT NULL CHECK (session_epoch > 0),
    enabled boolean NOT NULL,
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL
);
CREATE UNIQUE INDEX operators_login_identity ON space.operators(lower(login_name));
CREATE TABLE space.operator_sessions (
    session_hash bytea PRIMARY KEY CHECK (octet_length(session_hash) > 0),
    hash_version integer NOT NULL CHECK (hash_version > 0),
    operator_id bigint NOT NULL REFERENCES space.operators(id) ON DELETE CASCADE,
    session_epoch bigint NOT NULL CHECK (session_epoch > 0),
    csrf_hash bytea NOT NULL CHECK (octet_length(csrf_hash) > 0),
    created_at space.instant_ns NOT NULL,
    expires_at space.instant_ns NOT NULL,
    revoked_at space.instant_ns,
    CHECK (expires_at > created_at)
);
CREATE INDEX operator_sessions_owner ON space.operator_sessions(operator_id, expires_at);

CREATE TABLE space.mail_sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('apple_direct', 'apple_forwarded', 'custom')),
    display_name text NOT NULL,
    address_namespace text NOT NULL CHECK (address_namespace <> ''),
    imap_host text NOT NULL CHECK (imap_host <> ''),
    imap_port integer NOT NULL CHECK (imap_port BETWEEN 1 AND 65535),
    imap_username text NOT NULL CHECK (imap_username <> ''),
    credentials_envelope bytea CHECK (credentials_envelope IS NULL OR octet_length(credentials_envelope) > 0),
    address_suffix text NOT NULL,
    enabled boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    source_generation bigint NOT NULL CHECK (source_generation > 0),
    credential_generation bigint NOT NULL CHECK (credential_generation > 0),
    automatic_sync_after space.instant_ns,
    last_terminal_sync_at space.instant_ns,
    last_sync_state text NOT NULL DEFAULT '',
    last_sync_error text NOT NULL DEFAULT '',
    last_synced_at space.instant_ns,
    retired_at space.instant_ns,
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL,
    CHECK (retired_at IS NOT NULL OR (credentials_envelope IS NOT NULL AND octet_length(credentials_envelope) > 0)),
    CHECK (retired_at IS NULL OR NOT enabled)
);
CREATE UNIQUE INDEX mail_sources_active_namespace ON space.mail_sources(address_namespace) WHERE retired_at IS NULL;
CREATE INDEX mail_sources_metadata ON space.mail_sources(created_at DESC, id DESC);
CREATE INDEX mail_sources_enabled ON space.mail_sources(enabled, id);
CREATE INDEX mail_sources_search ON space.mail_sources(lower(display_name), id);
CREATE TABLE space.apple_principals (
    source_id bigint PRIMARY KEY REFERENCES space.mail_sources(id) ON DELETE CASCADE,
    apple_id text NOT NULL CHECK (apple_id <> ''),
    region text NOT NULL CHECK (region IN ('global', 'china')),
    dsid text,
    revision bigint NOT NULL CHECK (revision > 0)
);
CREATE TABLE space.apple_sessions (
    source_id bigint PRIMARY KEY REFERENCES space.apple_principals(source_id) ON DELETE CASCADE,
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    principal_revision bigint NOT NULL CHECK (principal_revision > 0),
    session_envelope bytea NOT NULL CHECK (octet_length(session_envelope) > 0),
    authenticated boolean NOT NULL DEFAULT false,
    last_validated_at space.instant_ns,
    created_at space.instant_ns NOT NULL DEFAULT space.clock_ns(),
    saved_at space.instant_ns NOT NULL,
    expires_at space.instant_ns
);
CREATE TABLE space.apple_challenges (
    challenge_hash bytea PRIMARY KEY CHECK (octet_length(challenge_hash) > 0),
    source_id bigint NOT NULL REFERENCES space.apple_principals(source_id) ON DELETE CASCADE,
    operator_id bigint NOT NULL REFERENCES space.operators(id) ON DELETE CASCADE,
    principal_revision bigint NOT NULL CHECK (principal_revision > 0),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    session_revision bigint NOT NULL DEFAULT 1 CHECK (session_revision > 0),
    request_key text,
    state text NOT NULL CHECK (state IN ('password', 'mfa', 'complete', 'failed', 'expired')),
    challenge_envelope bytea NOT NULL,
    attempts integer NOT NULL CHECK (attempts >= 0),
    created_at space.instant_ns NOT NULL,
    expires_at space.instant_ns NOT NULL,
    CHECK (expires_at > created_at),
    UNIQUE (source_id, operator_id, request_key)
);

-- Every explicit provider action remains queryable by its original request
-- identifier without retaining the ephemeral challenge token in a browser.
CREATE TABLE space.apple_action_requests (
    source_id bigint NOT NULL REFERENCES space.apple_principals(source_id) ON DELETE CASCADE,
    operator_id bigint NOT NULL REFERENCES space.operators(id) ON DELETE CASCADE,
    request_key text NOT NULL CHECK (request_key <> ''),
    challenge_hash bytea NOT NULL REFERENCES space.apple_challenges(challenge_hash) ON DELETE CASCADE,
    PRIMARY KEY (source_id, operator_id, request_key)
);

CREATE TABLE space.address_groups (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text NOT NULL CHECK (display_name <> ''),
    normalized_name text NOT NULL CHECK (normalized_name <> ''),
    revision bigint NOT NULL DEFAULT 1 CHECK (revision > 0),
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL,
    UNIQUE (normalized_name)
);
CREATE TABLE space.private_addresses (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id > 0),
    source_id bigint NOT NULL REFERENCES space.mail_sources(id) ON DELETE CASCADE,
    email text NOT NULL CHECK (email <> ''),
    normalized_email text NOT NULL CHECK (normalized_email <> ''),
    kind text NOT NULL CHECK (kind IN ('apple', 'manual', 'random')),
    label text NOT NULL,
    group_id bigint,
    lifecycle text NOT NULL CHECK (lifecycle IN ('pending', 'confirmed', 'deletion_pending', 'archived')),
    enabled boolean NOT NULL,
    deleted_at space.instant_ns,
    archived_at space.instant_ns,
    archive_reason text CHECK (archive_reason IN ('remote_missing', 'historical')),
    provider_address_id text,
    provider_owner text,
    provider_active boolean,
    forwarding_email text,
    revision bigint NOT NULL CHECK (revision > 0),
    auth_generation bigint NOT NULL CHECK (auth_generation > 0),
    uid_validity bigint NOT NULL CHECK (uid_validity BETWEEN 1 AND 4294967295),
    uid_next bigint NOT NULL CHECK (uid_next BETWEEN 1 AND 4294967296),
    last_sync_state text NOT NULL DEFAULT '',
    last_sync_error text NOT NULL DEFAULT '',
    last_synced_at space.instant_ns,
    last_accessed_at space.instant_ns,
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL,
    UNIQUE (source_id, id),
    UNIQUE (source_id, provider_address_id),
    FOREIGN KEY (group_id) REFERENCES space.address_groups(id),
    CHECK (lifecycle = 'confirmed' OR NOT enabled),
    CHECK (deleted_at IS NULL OR NOT enabled),
    CHECK ((lifecycle = 'archived') = (archived_at IS NOT NULL AND archive_reason IS NOT NULL))
);
CREATE UNIQUE INDEX addresses_active_email ON space.private_addresses(normalized_email) WHERE deleted_at IS NULL;
CREATE INDEX addresses_source_page ON space.private_addresses(source_id, created_at DESC, id DESC);
CREATE INDEX addresses_group_page ON space.private_addresses(source_id, group_id, id);
CREATE INDEX addresses_lifecycle_page ON space.private_addresses(source_id, lifecycle, id);
CREATE INDEX addresses_label_search ON space.private_addresses(lower(label), id);

-- Effective permissions are facts. A retained encrypted bundle alone grants nothing.
CREATE TABLE space.address_grants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL,
    address_id bigint NOT NULL,
    purpose text NOT NULL CHECK (purpose IN ('latest_read', 'mail_read', 'mail_consume', 'raw_read', 'imap_login', 'oauth_client', 'oauth_refresh')),
    authenticator_kind text NOT NULL CHECK (authenticator_kind IN ('api_key', 'imap_password', 'client_id', 'refresh_token', 'opaque')),
    authenticator_hash bytea NOT NULL CHECK (octet_length(authenticator_hash) > 0),
    hash_scheme text NOT NULL CHECK (hash_scheme <> ''),
    hash_version integer NOT NULL CHECK (hash_version > 0),
    auth_generation bigint NOT NULL CHECK (auth_generation > 0),
    parent_grant_id bigint,
    issued_at space.instant_ns NOT NULL,
    expires_at space.instant_ns,
    revoked_at space.instant_ns,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE,
    FOREIGN KEY (source_id, address_id, parent_grant_id) REFERENCES space.address_grants(source_id, address_id, id),
    UNIQUE (address_id, purpose, authenticator_kind, authenticator_hash, auth_generation),
    UNIQUE (source_id, address_id, id),
    CHECK (expires_at IS NULL OR expires_at > issued_at)
);
CREATE INDEX grants_lookup ON space.address_grants(authenticator_kind, hash_scheme, authenticator_hash) WHERE revoked_at IS NULL;
CREATE TABLE space.address_credential_bundles (
    address_id bigint PRIMARY KEY,
    source_id bigint NOT NULL,
    bundle_envelope bytea NOT NULL CHECK (octet_length(bundle_envelope) > 0),
    bundle_version integer NOT NULL CHECK (bundle_version > 0),
    auth_generation bigint NOT NULL CHECK (auth_generation > 0),
    updated_at space.instant_ns NOT NULL,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE
);
CREATE TABLE space.pending_reveals (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL,
    address_id bigint NOT NULL,
    delivery_key text NOT NULL UNIQUE CHECK (delivery_key <> ''),
    owner_key text NOT NULL CHECK (owner_key <> ''),
    secret_envelope bytea NOT NULL CHECK (octet_length(secret_envelope) > 0),
    auth_generation bigint NOT NULL CHECK (auth_generation > 0),
    created_at space.instant_ns NOT NULL,
    acknowledged_at space.instant_ns,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE
);
CREATE INDEX pending_reveals_unacknowledged ON space.pending_reveals(owner_key, id) WHERE acknowledged_at IS NULL;

-- Deployment-authorized local registration owns an explicit request receipt.
-- Long-lived mailbox material remains in its existing credential owners.
CREATE TABLE space.external_registrations (
    operation_key text PRIMARY KEY CHECK (operation_key ~ '^[!-~]{1,128}$'),
    source_id bigint NOT NULL REFERENCES space.mail_sources(id) ON DELETE RESTRICT,
    owner_hash bytea NOT NULL CHECK (octet_length(owner_hash) = 32),
    request_digest bytea NOT NULL CHECK (octet_length(request_digest) = 32),
    normalized_email text NOT NULL CHECK (normalized_email <> '' AND normalized_email = lower(normalized_email)),
    delivery_owner text NOT NULL CHECK (delivery_owner <> ''),
    state text NOT NULL CHECK (state IN ('prepared', 'committed', 'cancelled')),
    address_id bigint,
    auth_generation bigint CHECK (auth_generation > 0),
    delivery_key text,
    created_at space.instant_ns NOT NULL,
    committed_at space.instant_ns,
    cancelled_at space.instant_ns,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE RESTRICT,
    UNIQUE (source_id, operation_key),
    CHECK ((state = 'prepared' AND address_id IS NULL AND auth_generation IS NULL AND delivery_key IS NULL AND committed_at IS NULL AND cancelled_at IS NULL)
        OR (state = 'committed' AND address_id IS NOT NULL AND auth_generation IS NOT NULL AND delivery_key IS NOT NULL AND committed_at IS NOT NULL AND cancelled_at IS NULL)
        OR (state = 'cancelled' AND address_id IS NULL AND auth_generation IS NULL AND delivery_key IS NULL AND committed_at IS NULL AND cancelled_at IS NOT NULL))
);
CREATE UNIQUE INDEX external_registrations_prepared_email ON space.external_registrations(normalized_email) WHERE state = 'prepared';

-- Object identity is independent of the source UID and shared by address entries.
-- Eviction never erases the expected byte count, digest, reference or publication generation.
CREATE TABLE space.content_objects (
    object_key text PRIMARY KEY CHECK (object_key <> '' AND object_key !~ '(^/|(^|/)\.\.(/|$))'),
    source_id bigint NOT NULL REFERENCES space.mail_sources(id) ON DELETE CASCADE,
    manifest_version integer NOT NULL CHECK (manifest_version > 0),
    byte_size bigint NOT NULL CHECK (byte_size >= 0),
    sha256 bytea NOT NULL CHECK (octet_length(sha256) = 32),
    storage_ref text NOT NULL CHECK (storage_ref <> ''),
    state text NOT NULL CHECK (state IN ('staged', 'available', 'evicted', 'missing', 'corrupt')),
    publication_generation bigint NOT NULL CHECK (publication_generation > 0),
    retention_order_at space.instant_ns NOT NULL,
    created_at space.instant_ns NOT NULL,
    published_at space.instant_ns,
    evicted_at space.instant_ns,
    verified_at space.instant_ns,
    UNIQUE (source_id, object_key),
    CHECK (state <> 'available' OR published_at IS NOT NULL)
);
CREATE INDEX content_retention_fifo ON space.content_objects(retention_order_at, object_key) WHERE state = 'available';
CREATE TABLE space.content_publications (
    receipt_key text PRIMARY KEY CHECK (receipt_key <> ''),
    source_id bigint NOT NULL,
    object_key text NOT NULL,
    owner_key text NOT NULL CHECK (owner_key <> ''),
    staging_ref text NOT NULL CHECK (staging_ref <> ''),
    publication_generation bigint NOT NULL CHECK (publication_generation > 0),
    state text NOT NULL CHECK (state IN ('staged', 'published', 'sql_unknown', 'committed', 'abandoned')),
    created_at space.instant_ns NOT NULL,
    updated_at space.instant_ns NOT NULL,
    FOREIGN KEY (source_id, object_key) REFERENCES space.content_objects(source_id, object_key) ON DELETE CASCADE,
    UNIQUE (object_key, publication_generation)
);
CREATE TABLE space.source_messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES space.mail_sources(id) ON DELETE CASCADE,
    source_generation bigint NOT NULL CHECK (source_generation > 0),
    mailbox_name text NOT NULL CHECK (mailbox_name <> ''),
    uid_validity bigint NOT NULL CHECK (uid_validity BETWEEN 1 AND 4294967295),
    remote_uid bigint NOT NULL CHECK (remote_uid BETWEEN 1 AND 4294967295),
    object_key text,
    rfc_message_id text NOT NULL,
    subject text NOT NULL,
    sender_address text NOT NULL,
    sender_name text NOT NULL,
    sender_descriptors jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(sender_descriptors) = 'array'),
    sent_at space.instant_ns,
    received_at space.instant_ns NOT NULL,
    raw_header bytea NOT NULL,
    raw_header_complete boolean NOT NULL DEFAULT false,
    preview_text text NOT NULL,
    declared_body_size bigint NOT NULL DEFAULT 0 CHECK (declared_body_size >= 0),
    declared_body_sha256 bytea CHECK (octet_length(declared_body_sha256) = 32),
    declared_body_truncated boolean NOT NULL DEFAULT false,
    content_state text NOT NULL CHECK (content_state IN ('complete', 'metadata_only', 'over_budget', 'malformed')),
    ingested_at space.instant_ns NOT NULL DEFAULT space.clock_ns(),
    created_at space.instant_ns NOT NULL,
    UNIQUE (source_id, source_generation, mailbox_name, uid_validity, remote_uid),
    UNIQUE (source_id, id),
    FOREIGN KEY (source_id, object_key) REFERENCES space.content_objects(source_id, object_key)
);
CREATE INDEX messages_source_time ON space.source_messages(source_id, received_at DESC, id DESC);
CREATE INDEX messages_source_uid ON space.source_messages(source_id, source_generation, mailbox_name, uid_validity, remote_uid);
-- A retained parsed view does not assert that the original MIME still exists.
-- It also permits importing a latest snapshot that predates body archival.
CREATE TABLE space.message_views (
    view_key text PRIMARY KEY CHECK (view_key <> ''),
    source_id bigint NOT NULL,
    message_id bigint NOT NULL,
    address_id bigint,
    scope_address_id bigint GENERATED ALWAYS AS (coalesce(address_id, 0)) STORED,
    view_version integer NOT NULL CHECK (view_version > 0),
    rfc_message_id text NOT NULL,
    subject text NOT NULL,
    sender_descriptors jsonb NOT NULL CHECK (jsonb_typeof(sender_descriptors) = 'array'),
    to_descriptors jsonb NOT NULL CHECK (jsonb_typeof(to_descriptors) = 'array'),
    cc_descriptors jsonb NOT NULL CHECK (jsonb_typeof(cc_descriptors) = 'array'),
    sent_at space.instant_ns,
    received_at space.instant_ns NOT NULL,
    text_body text NOT NULL,
    html_body text NOT NULL,
    attachment_descriptors jsonb NOT NULL CHECK (jsonb_typeof(attachment_descriptors) = 'array'),
    body_complete boolean NOT NULL,
    derived_at space.instant_ns NOT NULL,
    FOREIGN KEY (source_id, message_id) REFERENCES space.source_messages(source_id, id) ON DELETE CASCADE,
    FOREIGN KEY (source_id, address_id) REFERENCES space.private_addresses(source_id, id) ON DELETE CASCADE,
    UNIQUE NULLS NOT DISTINCT (message_id, address_id),
    UNIQUE (source_id, message_id, view_key, scope_address_id)
);
CREATE TABLE space.message_recipients (
    message_id bigint NOT NULL REFERENCES space.source_messages(id) ON DELETE CASCADE,
